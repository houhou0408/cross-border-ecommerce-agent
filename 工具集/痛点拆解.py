def _分析低评分竞品(竞品列表: List[Dict]) -> List[Dict]:
    """从竞品列表中筛选需要分析的竞品。

    策略：
    1. 优先取评分 ≤4.2 的竞品
    2. 若无低分竞品，取评分最低的 3 个（即使评分不低）
    3. 返回带痛点标签的竞品列表。
    """
    # 按评分升序排列
    有序 = sorted(
        [c for c in 竞品列表 if isinstance(c.get("评分"), (int, float))],
        key=lambda c: c.get("评分", 5)
    )
    if not 有序:
        return []

    低评 = [c for c in 有序 if c["评分"] <= 4.2]
    if 低评:
        return 低评
    # 无真正低分竞品时，取评分最低的 3 个做相对分析
    return 有序[:3]


def _推断痛点类型(竞品: Dict, 所有价格: List[float]) -> Tuple[str, str]:
    """根据单个竞品的评分/评论数/价格，推断其痛点类型。

    Returns:
        (痛点类型, 具体理由)
    """
    评分 = 竞品.get("评分") or 0
    评论数 = 竞品.get("评论数") or 0
    价格 = 竞品.get("价格") or 0

    # 规则优先级从高到低
    if 评分 < 3.5 and 评论数 > 1000:
        return "产品质量通病", f"评分{评分}★+{评论数}条评论->大量用户反馈质量问题"
    if 评分 < 4.0 and 评论数 < 50:
        return "新品质量不稳", f"评分{评分}★+仅{评论数}条评论->新品品控尚未稳定"
    if 价格 > 0 and 所有价格:
        中位价格 = sorted(所有价格)[len(所有价格)//2] if 所有价格 else 价格
        if 价格 > 中位价格 * 1.3 and 评分 < 4.0:
            return "性价比问题", f"定价${价格}高于市场中位${中位价格:.0f}但评分仅{评分}★->性价比差"
    if 评论数 > 500 and 评分 < 4.2:
        return "细节问题常见", f"{评论数}条评论但评分{评分}★->用户对细节体验不满"
    # 高分但相对较低的竞品：虽不差但存在可优化空间
    if 评论数 > 100 and 评分 < 4.4:
        return "细节问题常见", f"评分{评分}★{评论数}条评论->相对同品类偏低，细节体验有优化空间"
    if 评论数 > 0 and 评分 < 4.5:
        return "细节问题常见", f"评分{评分}★偏低，存在可改进的用户体验问题"
    # 兜底
    if 评分 < 4.0:
        return "产品质量通病", f"评分{评分}★偏低，建议深入分析用户评论"
    return "细节问题常见", f"评分{评分}★在类目中属中等偏下，针对性优化可拉开差距"


def _统计痛点分布(低评分竞品: List[Dict]) -> List[Dict]:
    """对低评分竞品按痛点类型聚合统计。

    Returns:
        [{"类型": "产品质量通病", "竞品": [竞品1, 竞品2, ...], "数量": 2}, ...]
    """
    所有价格 = [c.get("价格") for c in 低评分竞品
               if isinstance(c.get("价格"), (int, float)) and c.get("价格", 0) > 0]

    痛点分组: Dict[str, Dict] = {}
    for c in 低评分竞品:
        类型, 理由 = _推断痛点类型(c, 所有价格)
        if 类型 not in 痛点分组:
            痛点分组[类型] = {"类型": 类型, "竞品": [], "数量": 0}
        痛点分组[类型]["竞品"].append({**c, "推断理由": 理由})
        痛点分组[类型]["数量"] += 1

    # 按数量降序排列
    return sorted(痛点分组.values(), key=lambda x: x["数量"], reverse=True)


def 分析竞品痛点(品类: str, 目标市场: str = "美国") -> Dict[str, Any]:
    """从竞品数据中分析用户痛点，找出市场短板及差异化爆款机会。

    分析步骤：
    1. 调用 fetch_rainforest_competitors 获取竞品列表
    2. 按评分排序，找出低评分(≤4.2)竞品；无低分则取底部3名
    3. 分析低评分竞品的特征模式（价格区间、品类共性）
    4. 基于评分分布 + 评论数分布推断痛点类型
    5. 调用 fetch_rainforest_reviews 获取评分最低竞品的真实用户评论
    6. 为每个推断痛点生成差异化改款建议

    Args:
        品类: 商品品类（如 电子产品、服装、家居、美妆、宠物用品）
        目标市场: 目标市场（如 美国、欧盟、日本）

    Returns:
        dict: {
            "品类": str,
            "市场": str,
            "数据来源": str,
            "分析时间": str,
            "竞品总数": int,
            "低评分竞品数": int,
            "平均评分": str,
            "痛点列表": [{"类型": str, "数量": int, "问题描述": str, "改款方向": str, "差异化卖点": str, "优先度": str, "受影响竞品": [dict]}, ...],
        }
    """
    # 1) 采集真实竞品数据
    竞品数据 = fetch_rainforest_competitors(品类, 目标市场)
    数据来源 = "Rainforest API"

    if 竞品数据 and 竞品数据.get("竞品列表"):
        竞品列表 = 竞品数据["竞品列表"]
        数据来源 = 竞品数据.get("数据来源", "Rainforest API")
        amazon_domain = 竞品数据.get("域名", "amazon.com")
    else:
        # 降级：无真实数据时返回基于品类基线评分的信息
        return _降级分析(品类, 目标市场)

    # 2) 统计分析
    竞品总数 = len(竞品列表)
    有效评分 = [c["评分"] for c in 竞品列表
               if isinstance(c.get("评分"), (int, float))]
    平均评分 = round(sum(有效评分) / len(有效评分), 1) if 有效评分 else 0

    # 3) 筛选低评分竞品 + 痛点归类
    低评分 = _分析低评分竞品(竞品列表)
    痛点分布 = _统计痛点分布(低评分)

    # 3.5) 获取评分最低竞品的真实用户评论（评论分析）
    真实评论 = None
    if 低评分:
        评分最低 = sorted(低评分, key=lambda c: c.get("评分", 5))[0]
        if 评分最低.get("asin"):
            真实评论 = fetch_rainforest_reviews(评分最低["asin"], amazon_domain)

    # 4) 生成完整痛点报告
    痛点列表 = []
    for item in 痛点分布:
        方案 = _改进方案.get(item["类型"], _改进方案["细节问题常见"])
        受影响竞品 = item["竞品"]  # 全部展示，不做截断

        痛点详情 = {
            "类型": item["类型"],
            "数量": item["数量"],
            "问题描述": 方案["问题"],
            "改款方向": 方案["改款方向"],
            "差异化卖点": 方案["差异化卖点"],
            "优先度": 方案["优先度"],
            "受影响竞品": [
                {
                    "标题": (c.get("标题") or "")[:60],
                    "价格": c.get("价格"),
                    "评分": c.get("评分"),
                    "评论数": c.get("评论数"),
                    "推断理由": c.get("推断理由", ""),
                }
                for c in 受影响竞品
            ],
        }
        痛点列表.append(痛点详情)

    # 5) 竞品太少的情况
    if 竞品总数 < 3:
        方案 = _改进方案["竞品太少"]
        # 避免重复添加
        if not any(p["类型"] == "竞品太少" for p in 痛点列表):
            痛点列表.insert(0, {
                "类型": "竞品太少",
                "数量": 0,
                "问题描述": 方案["问题"],
                "改款方向": 方案["改款方向"],
                "差异化卖点": 方案["差异化卖点"],
                "优先度": 方案["优先度"],
                "受影响竞品": [],
            })

    return {
        "品类": 品类,
        "市场": 目标市场,
        "数据来源": 数据来源,
        "分析时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "竞品总数": 竞品总数,
        "低评分竞品数": len(低评分),
        "平均评分": f"{平均评分}★",
        "痛点列表": 痛点列表,
        "评论分析": 真实评论,  # 评分最低竞品的真实用户评论片段
    }


def _降级分析(品类: str, 目标市场: str) -> Dict[str, Any]:
    """无真实竞品数据时的降级方案：基于品类基线评分配置推断痛点。"""
    基线 = _品类基线评分.get(品类, {
        "平均评分": 4.0,
        "常见痛点": ["品质不稳定", "功能细节", "性价比"],
    })

    痛点列表 = []
    for i, 痛点 in enumerate(基线.get("常见痛点", [])):
        # 将品类常见痛点映射到已有改进方案
        if "电池" in 痛点 or "耐用" in 痛点 or "做工" in 痛点 or "品质" in 痛点:
            类型 = "产品质量通病"
        elif "尺寸" in 痛点 or "安装" in 痛点 or "异味" in 痛点 or "色差" in 痛点:
            类型 = "细节问题常见"
        elif "价格" in 痛点 or "性价比" in 痛点:
            类型 = "性价比问题"
        else:
            类型 = "细节问题常见"

        方案 = _改进方案[类型]
        痛点列表.append({
            "类型": 类型,
            "数量": 0,
            "问题描述": f"{方案['问题']}（基于{品类}品类基线推断：{痛点}）",
            "改款方向": 方案["改款方向"],
            "差异化卖点": 方案["差异化卖点"],
            "优先度": 方案["优先度"],
            "受影响竞品": [],
        })

    return {
        "品类": 品类,
        "市场": 目标市场,
        "数据来源": "品类基线推断（Rainforest API 不可用）",
        "分析时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "竞品总数": 0,
        "低评分竞品数": 0,
        "平均评分": f"{基线.get('平均评分', 4.0)}★（估算）",
        "痛点列表": 痛点列表,
    }


# ============ Agent 工具注册 ============

@tool("analyze_pain_points")
def 痛点分析(品类: str, 目标市场: str = "美国") -> str:
    """深度分析竞品用户痛点，输出差异化改款建议。

    当用户要求"分析痛点""看看用户吐槽什么""竞品有什么问题"时调用。
    自动从 Rainforest API 获取真实竞品数据，基于评分/评论分析常见问题模式，
    输出每条痛点的改进方案和差异化卖点。

    Args:
        品类: 商品品类（如 电子产品、服装、家居）
        目标市场: 目标市场（如 美国、欧盟、日本）

    Returns:
        格式化的 Markdown 痛点分析报告
    """
    result = 分析竞品痛点(品类, 目标市场)

    lines = [
        "## 竞品痛点深度分析",
        "",
        "### 数据基础",
        f"- 分析竞品数: {result['竞品总数']}个",
        f"- 低评分竞品(≤4.2): {result['低评分竞品数']}个",
        f"- 平均评分: {result['平均评分']}",
        f"- 数据来源: {result['数据来源']}",
        f"- 分析时间: {result['分析时间']}",
    ]

    痛点列表 = result.get("痛点列表", [])
    if not 痛点列表:
        lines.append("")
        lines.append("### 分析结论")
        lines.append("暂未发现明显的竞品痛点，该品类整体表现良好。")
        return "\n".join(lines)

    for i, 痛点 in enumerate(痛点列表, 1):
        lines.append("")
        lines.append(f"### 痛点{i}: {痛点['类型']}")
        lines.append(f"- 问题描述: {痛点['问题描述']}")
        lines.append(f"- 影响竞品数: {痛点['数量']}个")
        受影响 = 痛点.get("受影响竞品", [])
        if 受影响:
            for comp in 受影响:
                价格显示 = f"${comp['价格']}" if comp.get("价格") else "暂无价格"
                评分显示 = f"{comp['评分']}★" if comp.get("评分") else "暂无评分"
                评论显示 = f"{comp['评论数']}评论" if comp.get("评论数") else "暂无评论"
                lines.append(f"  - {comp['标题'][:50]} ({价格显示}, {评分显示}, {评论显示})")
                if comp.get("推断理由"):
                    lines.append(f"    → {comp['推断理由']}")
        lines.append(f"- 改款方案: {痛点['改款方向']}")
        lines.append(f"- 差异化卖点: \"{痛点['差异化卖点']}\"")
        if 痛点.get("优先度"):
            lines.append(f"- **优先度: {痛点['优先度']}**")

    # 展示真实评论分析
    评论分析 = result.get("评论分析")
    if 评论分析 and isinstance(评论分析, dict):
        reviews_list = 评论分析.get("reviews", [])
        if reviews_list:
            lines.append("")
            lines.append("### 真实用户评论分析")
            lines.append(f"- 数据来源: ASIN {评论分析.get('asin', '')}（评分最低竞品）")
            for review in reviews_list:  # 全部展示
                title = review.get("title", "")
                body = review.get("body", "")
                rating = review.get("rating", "")
                if title:
                    lines.append(f"- {rating}★ {title[:120]}")
                if body:
                    lines.append(f"  {body[:250]}")

    lines.append("")
    lines.append("### 综合建议")
    高优先 = [p for p in 痛点列表 if p.get("优先度") == "最高"]
    if 高优先:
        lines.append(f"- {len(高优先)}个最高优先度痛点需立即处理，否则错失差异化窗口期")
    中优先 = [p for p in 痛点列表 if p.get("优先度") in ("高", "中")]
    if 中优先:
        lines.append(f"- {len(中优先)}个中高优先度痛点可作为产品迭代方向")
    lines.append("- 所有分析基于真实竞品评分/评论数据，非凭空推断")
    lines.append("- 建议结合 Rainforest API 详细评论接口进一步验证痛点准确性")

    return "\n".join(lines)
