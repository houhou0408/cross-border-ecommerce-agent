@tool("query_logistics")
def 物流时效查询(发货地: str, 目的国: str, 物流方式: str) -> str:
    """查询指定发货地→目的国、物流方式的预计时效、运费区间与适用场景。

    Args:
        发货地: 发货地，如 中国
        目的国: 目的国/地区，如 美国、欧洲、日本、东南亚
        物流方式: 物流方式，如 海运、空运、快递、铁路

    Returns:
        预计时效、运费区间、适用场景建议的说明文本
    """
    info = None
    # 1) 优先查库
    with get_cursor() as cur:
        if cur is not None:
            cur.execute(
                "SELECT duration, freight_range, scenario "
                "FROM logistics_route WHERE origin=%s AND destination=%s AND mode=%s",
                (发货地, 目的国, 物流方式),
            )
            row = cur.fetchone()
            if row:
                info = {
                    "时效": row["duration"],
                    "运费区间": row["freight_range"],
                    "场景": row.get("scenario", ""),
                }

    # 2) 降级到内置数据
    if info is None:
        info = MOCK_LOGISTICS.get((发货地, 目的国, 物流方式))

    if info is None:
        return f"未查询到【{发货地}→{目的国} / {物流方式}】的物流线路，建议核实线路或补充货代报价。"

    lines = [
        f"发货地: {发货地}",
        f"目的国: {目的国}",
        f"物流方式: {物流方式}",
        f"预计时效: {info['时效']}",
        f"运费区间: {info['运费区间']}",
        f"适用场景: {info['场景']}",
    ]
    return "\n".join(lines)
