@tool("analyze_product")
def 选品分析(品类: str, 目标市场: str) -> str:
    """基于品类与目标市场，给出选品建议（市场热度/竞争程度/利润空间/合规风险/推荐指数）。

    Args:
        品类: 商品品类，如 电子产品、服装、家居、美妆、宠物用品
        目标市场: 目标市场/地区，如 美国、东南亚、欧盟、日本

    Returns:
        市场热度、竞争程度、利润空间、合规风险、推荐指数及选品建议的说明文本
    """
    info = None
    # 1) 优先查库
    with get_cursor() as cur:
        if cur is not None:
            cur.execute(
                "SELECT heat, competition, profit_margin, compliance_risk, recommend_index, advice "
                "FROM product_selection WHERE category=%s AND market=%s",
                (品类, 目标市场),
            )
            row = cur.fetchone()
            if row:
                info = {
                    "市场热度": row["heat"],
                    "竞争程度": row["competition"],
                    "利润空间": row["profit_margin"],
                    "合规风险": row["compliance_risk"],
                    "推荐指数": int(row["recommend_index"]),
                    "建议": row.get("advice", ""),
                }

    # 2) 降级到内置数据
    if info is None:
        info = MOCK_SELECTION.get((品类, 目标市场))

    if info is None:
        return f"未查询到【{品类}-{目标市场}】的选品数据，建议补充该品类/市场的调研快照。"

    # 推荐指数转星级展示
    stars = "★" * info["推荐指数"] + "☆" * (5 - info["推荐指数"])
    lines = [
        f"品类: {品类}",
        f"目标市场: {目标市场}",
        f"市场热度: {info['市场热度']}",
        f"竞争程度: {info['竞争程度']}",
        f"利润空间: {info['利润空间']}",
        f"合规风险: {info['合规风险']}",
        f"推荐指数: {info['推荐指数']}/5 {stars}",
        f"选品建议: {info['建议']}",
    ]
    return "\n".join(lines)
