# -*- coding: utf-8 -*-
"""利润计算工具：按售价/成本/运费/关税/平台费率计算毛利、毛利率、利润率，并给出健康度评价。

说明：
- 毛利 = 售价 - 采购成本；
- 平台费 = 售价 × 平台费率；
- 净利润 = 售价 - 采购成本 - 运费 - 关税 - 平台费；
- 利润率 = 净利润 / 售价；
- 健康度评价以利润率为准：>30% 优秀，15%-30% 正常，<15% 需优化。
"""
from langchain_core.tools import tool


@tool("calc_profit")
def 利润计算(售价: float, 采购成本: float, 运费: float, 关税: float, 平台费率: float = 0.15) -> str:
    """计算跨境电商单件商品的毛利、毛利率、利润率，并给出利润健康度评价。

    Args:
        售价: 商品销售单价
        采购成本: 单件采购/制造成本
        运费: 单件分摊的国际运费
        关税: 单件应缴关税（可由 查询关税 工具计算）
        平台费率: 平台佣金率，默认0.15（即15%）

    Returns:
        毛利、毛利率、净利润、利润率及健康度评价的说明文本
    """
    if 售价 <= 0:
        return "售价必须大于0，请检查输入。"

    # 各项成本与利润
    平台费 = 售价 * 平台费率
    毛利 = 售价 - 采购成本
    净利润 = 售价 - 采购成本 - 运费 - 关税 - 平台费
    毛利率 = 毛利 / 售价
    利润率 = 净利润 / 售价

    # 健康度评价（以利润率为准）
    if 利润率 > 0.30:
        评价 = "优秀（利润率>30%，具备较强抗风险与推广空间）"
    elif 利润率 >= 0.15:
        评价 = "正常（利润率15%-30%，需控制成本维持健康）"
    else:
        评价 = "需优化（利润率<15%，建议压缩采购/运费/关税或提升售价）"

    lines = [
        f"售价: {售价:.2f}",
        f"采购成本: {采购成本:.2f}",
        f"运费: {运费:.2f}",
        f"关税: {关税:.2f}",
        f"平台费: {平台费:.2f}（费率{平台费率*100:.1f}%）",
        f"毛利: {毛利:.2f}（毛利率 {毛利率*100:.2f}%）",
        f"净利润: {净利润:.2f}（利润率 {利润率*100:.2f}%）",
        f"利润健康度: {评价}",
    ]
    return "\n".join(lines)
